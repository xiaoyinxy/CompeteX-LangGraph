"""研究报告自动评测使用的 Prompt。"""

OVERALL_QUALITY_PROMPT = """你是一名负责评估研究报告质量的专业评测员。请从多个维度评估给定报告，提供评分并给出综合评价。

评估标准：

1. 研究深度与完整性
   - 分析是否充分；
   - 是否覆盖用户问题的相关方面；
   - 理解是否深入；
   - 是否提供必要背景。

2. 来源质量与研究方法
   - 是否使用权威网页来源；
   - 来源类型是否多样，例如新闻、论文等；
   - 引用质量及与正文的结合程度；
   - 研究方法是否透明。

3. 分析严谨性
   - 分析是否具有深度；
   - 是否对来源信息进行批判性评估；
   - 是否识别细微差异和局限性。

4. 实用价值与可执行性
   - 洞察和建议是否清晰；
   - 是否提供具体示例和使用场景；
   - 报告中不得以报告撰写者身份进行自我指代。

5. 平衡性与客观性
   - 是否呈现多个视角；
   - 是否承认局限与取舍；
   - 是否区分事实和观点；
   - 是否避免偏见。

6. 写作质量与清晰度
   - 表达是否清晰、专业；
   - 术语使用是否恰当；
   - 语气和风格是否一致；
   - 是否易读；
   - 报告中不得以报告撰写者身份进行自我指代。

评分说明：
每个维度采用 1—5 分：
1 = 很差
2 = 较差
3 = 良好
4 = 很好
5 = 优秀

评估流程：
1. 先分别分析每个维度，并使用 <dimension_analysis> 标签包裹对应分析。每个维度需要：
   a) 引用报告中的相关内容；
   b) 列出优点与缺点；
   c) 分析其满足评估标准的程度。
   为了充分分析，这部分可以较长。
2. 完成分析后，按照下列格式给出正式评价。

补充考虑：
- 报告深度是否与主题复杂度相匹配；
- 报告是否有效服务于目标读者；
- 信息是否具有时效性和相关性；
- 关键方面是否得到充分覆盖；
- 在适当情况下是否结合量化数据、案例和具体示例。

输出格式：

各维度评分：
1. 研究深度与完整性：[评分]/5
   理由：[结合示例的简要说明]

2. 来源质量与研究方法：[评分]/5
   理由：[结合示例的简要说明]

3. 分析严谨性：[评分]/5
   理由：[结合示例的简要说明]

4. 实用价值与可执行性：[评分]/5
   理由：[结合示例的简要说明]

5. 平衡性与客观性：[评分]/5
   理由：[结合示例的简要说明]

6. 写作质量与清晰度：[评分]/5
   理由：[结合示例的简要说明]

综合评价：
[用 2—3 个自然段总结报告质量、实用价值和目标适配度]

今天的日期是 {today}。

现在请评估这份研究报告。
"""


